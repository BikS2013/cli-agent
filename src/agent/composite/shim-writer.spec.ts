describe('generatePathSymlink', () => {
  let workDir: string;
  let shimDir: string;
  let linkDir: string;
  let shimPath: string;

  beforeEach(async () => {
    workDir = await makeTmpDir('shim-writer-symlink');
    shimDir = path.join(workDir, 'shims');
    linkDir = path.join(workDir, 'bin');
    await fsp.mkdir(shimDir, { recursive: true });
    // Synthesise an actual shim file the symlink will point at.
    const result = await generateCompositeWrapperShim(makeSpec({ shimDir }));
    shimPath = result.path;
  });

  afterEach(async () => {
    await fsp.rm(workDir, { recursive: true, force: true });
  });

  it('happy path: creates a symlink in the requested directory', async () => {
    const r = await generatePathSymlink(shimPath, 'foo-plus-bar', { dir: linkDir });
    expect(r.symlinkPath).toBe(path.join(linkDir, 'foo-plus-bar'));
    const lstat = await fsp.lstat(r.symlinkPath);
    expect(lstat.isSymbolicLink()).toBe(true);
    const target = await fsp.readlink(r.symlinkPath);
    expect(target).toBe(shimPath);
  });

  it('idempotent: re-running with an already-correct symlink is a no-op', async () => {
    await generatePathSymlink(shimPath, 'foo-plus-bar', { dir: linkDir });
    const r = await generatePathSymlink(shimPath, 'foo-plus-bar', { dir: linkDir });
    expect(r.symlinkPath).toBe(path.join(linkDir, 'foo-plus-bar'));
    const target = await fsp.readlink(r.symlinkPath);
    expect(target).toBe(shimPath);
  });

  it('refuses to clobber an existing regular file when force is false', async () => {
    await fsp.mkdir(linkDir, { recursive: true });
    const collidePath = path.join(linkDir, 'foo-plus-bar');
    await fsp.writeFile(collidePath, 'pre-existing real binary', 'utf8');
    await expect(
      generatePathSymlink(shimPath, 'foo-plus-bar', { dir: linkDir }),
    ).rejects.toThrow(/already exists/);
    // Original file untouched.
    expect(await fsp.readFile(collidePath, 'utf8')).toBe('pre-existing real binary');
  });

  it('replaces an existing regular file when force=true and warns about it', async () => {
    await fsp.mkdir(linkDir, { recursive: true });
    const collidePath = path.join(linkDir, 'foo-plus-bar');
    await fsp.writeFile(collidePath, 'pre-existing real binary', 'utf8');

    const r = await generatePathSymlink(shimPath, 'foo-plus-bar', {
      dir: linkDir,
      force: true,
    });
    expect(r.symlinkPath).toBe(collidePath);
    const lstat = await fsp.lstat(collidePath);
    expect(lstat.isSymbolicLink()).toBe(true);
    expect(r.warnings.some((w) => /Replaced a non-symlink file/.test(w))).toBe(true);
  });

  it('replaces a stale symlink (pointing elsewhere) when force=true', async () => {
    await fsp.mkdir(linkDir, { recursive: true });
    const otherTarget = path.join(workDir, 'other-bin');
    await fsp.writeFile(otherTarget, '#!/bin/sh\necho other\n', { mode: 0o755 });
    const collidePath = path.join(linkDir, 'foo-plus-bar');
    await fsp.symlink(otherTarget, collidePath);

    const r = await generatePathSymlink(shimPath, 'foo-plus-bar', {
      dir: linkDir,
      force: true,
    });
    expect(await fsp.readlink(r.symlinkPath)).toBe(shimPath);
  });

  it('warns when the symlink directory is not on $PATH', async () => {
    const original = process.env['PATH'];
    process.env['PATH'] = '/usr/bin:/bin'; // does not contain linkDir
    try {
      const r = await generatePathSymlink(shimPath, 'foo-plus-bar', { dir: linkDir });
      expect(r.warnings.some((w) => /not on \$PATH/.test(w))).toBe(true);
    } finally {
      if (original === undefined) delete process.env['PATH'];
      else process.env['PATH'] = original;
    }
  });

  it('does NOT warn about $PATH when the symlink directory is on $PATH', async () => {
    const original = process.env['PATH'];
    process.env['PATH'] = `${linkDir}:/usr/bin:/bin`;
    try {
      const r = await generatePathSymlink(shimPath, 'foo-plus-bar', { dir: linkDir });
      expect(r.warnings.some((w) => /not on \$PATH/.test(w))).toBe(false);
    } finally {
      if (original === undefined) delete process.env['PATH'];
      else process.env['PATH'] = original;
    }
  });

  it('rejects a name containing a path separator', async () => {
    await expect(
      generatePathSymlink(shimPath, 'evil/name', { dir: linkDir }),
    ).rejects.toThrow(/invalid name/);
  });
});
