describe('generateCompositeWrapperShim — nvm/volta/asdf detection', () => {
  let outDir: string;
  beforeEach(async () => {
    outDir = await makeTmpDir('shim-writer-vm');
  });
  afterEach(async () => {
    await fsp.rm(outDir, { recursive: true, force: true });
  });

  it.each([
    ['nvm', '/Users/x/.nvm/versions/node/v22.0.0/bin/cli-agent'],
    ['volta', '/Users/x/.volta/bin/cli-agent'],
    ['asdf', '/Users/x/.asdf/installs/nodejs/22.0.0/bin/cli-agent'],
  ])('warns when cliAgentBinPath is under %s', async (manager, binPath) => {
    const result = await generateCompositeWrapperShim(
      makeSpec({ shimDir: outDir, cliAgentBinPath: binPath }),
    );
    expect(result.warnings.length).toBeGreaterThan(0);
    expect(result.warnings.join(' ')).toContain(manager);
    // Shim still emitted (non-fatal warning per OQ-6).
    const body = await fsp.readFile(result.path, 'utf8');
    expect(body).toContain(`exec '${binPath}'`);
  });

  it('does NOT warn for a stable global install path', async () => {
    const result = await generateCompositeWrapperShim(
      makeSpec({ shimDir: outDir, cliAgentBinPath: '/usr/local/bin/cli-agent' }),
    );
    expect(result.warnings).toEqual([]);
  });
});

