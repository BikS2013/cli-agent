/* mode + atomicity                                                    */
/* ------------------------------------------------------------------ */

describe('generateCompositeWrapperShim — atomic write & mode', () => {
  let outDir: string;
  beforeEach(async () => {
    outDir = await makeTmpDir('shim-writer-atomic');
  });
  afterEach(async () => {
    await fsp.rm(outDir, { recursive: true, force: true });
  });

  it('writes the shim with mode 0o755', async () => {
    const result = await generateCompositeWrapperShim(makeSpec({ shimDir: outDir }));
    expect(result.mode).toBe(0o755);
    const stat = await fsp.stat(result.path);
    // Mask off the file-type bits; only the permission bits matter.
    expect(stat.mode & 0o777).toBe(0o755);
  });

  it('cleans up the .tmp file when the rename fails (atomic-write semantics)', async () => {
    // Strategy: pre-create a directory at the FINAL path; rename(file → dir)
    // with a non-empty dir fails on POSIX (EISDIR / ENOTEMPTY / EEXIST,
    // depending on the platform). The writeFile of the .tmp succeeds, so
    // the cleanup path of the generator is exercised.
    const spec = makeSpec({ shimDir: outDir });
    const finalPath = path.join(outDir, spec.compositeName);
    await fsp.mkdir(finalPath);
    // Make the dir non-empty so rename can't atomically replace it on Linux.
    await fsp.writeFile(path.join(finalPath, 'sentinel'), 'x', 'utf8');

    await expect(generateCompositeWrapperShim(spec)).rejects.toThrow(/failed to write shim/);

    // Tmp file must NOT exist (cleaned up).
    const tmpPath = `${finalPath}.tmp`;
    await expect(fsp.stat(tmpPath)).rejects.toMatchObject({ code: 'ENOENT' });

    // Final path is unchanged (still our pre-existing directory).
    const stat = await fsp.lstat(finalPath);
    expect(stat.isDirectory()).toBe(true);
  });

  it('cleans up the .tmp file when writeFile itself fails (forced via read-only dir)', async () => {
    // Sub-strategy: chmod the parent dir to read-only (0o555) AFTER the
    // generator ensures it exists — but the generator does an mkdir first
    // with mode 0o700. We sidestep this by giving the generator a path
    // that already exists as a read-only directory.
    const lockedDir = path.join(outDir, 'locked');
    await fsp.mkdir(lockedDir, { mode: 0o500 });
    try {
      const spec = makeSpec({ shimDir: lockedDir });
      await expect(generateCompositeWrapperShim(spec)).rejects.toThrow(/failed to write shim/);
      // Tmp file should not exist (either never created, or cleaned up).
      const tmpPath = path.join(lockedDir, `${spec.compositeName}.tmp`);
      await expect(fsp.stat(tmpPath)).rejects.toMatchObject({ code: 'ENOENT' });
    } finally {
      // Restore writability so afterEach's rm() can succeed.
      await fsp.chmod(lockedDir, 0o700);
    }
  });

  it('idempotent: re-running with the same spec produces byte-identical content (modulo timestamp)', async () => {
    const spec1 = makeSpec({ shimDir: outDir, synthesizedAt: '2026-05-02T00:00:00.000Z' });
    const spec2 = makeSpec({ shimDir: outDir, synthesizedAt: '2026-05-03T00:00:00.000Z' });

    const r1 = await generateCompositeWrapperShim(spec1);
    const body1 = await fsp.readFile(r1.path, 'utf8');

    const r2 = await generateCompositeWrapperShim(spec2);
    const body2 = await fsp.readFile(r2.path, 'utf8');

    expect(r1.path).toBe(r2.path);
    expect(maskTimestamp(body1)).toBe(maskTimestamp(body2));
    // The bodies differ only in the timestamp comment.
    expect(body1).not.toBe(body2);
  });

  it('atomic rename: the final file at <outputDir>/<name> exists with full content (no half-written window)', async () => {
    const result = await generateCompositeWrapperShim(makeSpec({ shimDir: outDir }));
    const body = await fsp.readFile(result.path, 'utf8');
    expect(body.startsWith('#!/bin/sh\n')).toBe(true);
    expect(body.endsWith('\n')).toBe(true);
    // No leftover .tmp.
    await expect(fsp.stat(`${result.path}.tmp`)).rejects.toMatchObject({ code: 'ENOENT' });
  });
});

