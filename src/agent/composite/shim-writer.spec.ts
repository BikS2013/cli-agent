/**
 * Co-located unit tests for `shim-writer.ts` (plan-006 P6 / U-WRAPPER).
 *
 * Coverage:
 *   - shim text correctness (snapshot with the timestamp masked)
 *   - atomic-write semantics (tmp cleaned up on writeFile failure;
 *     final file untouched)
 *   - mode 0o755 verified via fsp.stat
 *   - idempotent regeneration (re-run produces same content modulo the
 *     timestamp comment)
 *   - nvm/volta/asdf detection emits warnings (non-fatal)
 *   - member-name escaping for awkward characters (space, single quote,
 *     backslash)
 *   - generatePathSymlink: happy path, collision-without-force,
 *     collision-with-force, on-PATH advisory.
 */

import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import * as fsp from 'node:fs/promises';
import * as os from 'node:os';
import * as path from 'node:path';

import {
  generateCompositeWrapperShim,
  generatePathSymlink,
} from './shim-writer.js';
import type { CompositeWrapperShimSpec } from './types.js';

/* ------------------------------------------------------------------ */
/* Fixture helpers                                                     */
/* ------------------------------------------------------------------ */

async function makeTmpDir(prefix: string): Promise<string> {
  return fsp.mkdtemp(path.join(os.tmpdir(), `${prefix}-`));
}

function makeSpec(overrides: Partial<CompositeWrapperShimSpec> = {}): CompositeWrapperShimSpec {
  return {
    compositeName: 'foo-plus-bar',
    members: ['foo-cli', 'bar-cli'],
    cliAgentBinPath: '/usr/local/bin/cli-agent',
    capabilityDocPath: '/home/u/.tool-agents/cli-agent/capabilities/foo-plus-bar.md',
    shimDir: '/tmp/never-used-default',
    synthesizedAt: '2026-05-02T12:00:00.000Z',
    ...overrides,
  };
}

/** Mask the timestamp comment so snapshot comparisons are stable. */
function maskTimestamp(text: string): string {
  return text.replace(
    /^# Generated by cli-agent composite-synthesize @ [^;]+; composite=/m,
    '# Generated by cli-agent composite-synthesize @ <ISO>; composite=',
  );
}

/* ------------------------------------------------------------------ */
/* generateCompositeWrapperShim                                        */
/* ------------------------------------------------------------------ */

describe('generateCompositeWrapperShim — shim text', () => {
  let outDir: string;

  beforeEach(async () => {
    outDir = await makeTmpDir('shim-writer-text');
  });

  afterEach(async () => {
    await fsp.rm(outDir, { recursive: true, force: true });
  });

  it('matches the recommended POSIX template (snapshot with masked timestamp)', async () => {
    const result = await generateCompositeWrapperShim(makeSpec({ shimDir: outDir }));
    const body = await fsp.readFile(result.path, 'utf8');
    const masked = maskTimestamp(body);

    expect(masked).toMatchInlineSnapshot(`
      "#!/bin/sh
      # Generated by cli-agent composite-synthesize @ <ISO>; composite=foo-plus-bar
      # cli-agent composite wrapper — foo-plus-bar
      # DO NOT HAND-EDIT — regenerate with:
      #   cli-agent --treat-as-tool --regenerate-capabilities --composite-name foo-plus-bar
      basedir=$(dirname "$(echo "$0" | sed -e 's,\\\\,/,g')")
      DOC='/home/u/.tool-agents/cli-agent/capabilities/foo-plus-bar.md'
      case "\${1:-}" in
        --help|-h)
          if [ ! -r "$DOC" ]; then
            echo "composite cache stale; re-run: cli-agent --treat-as-tool --regenerate-capabilities --composite-name foo-plus-bar" >&2
            exit 6
          fi
          exec cat "$DOC"
          ;;
      esac
      exec '/usr/local/bin/cli-agent' --tool 'foo-cli' --tool 'bar-cli' "$@"
      "
    `);
  });

  it('uses #!/bin/sh (no bash) and exec for the cli-agent invocation', async () => {
    const result = await generateCompositeWrapperShim(makeSpec({ shimDir: outDir }));
    const body = await fsp.readFile(result.path, 'utf8');
    expect(body.startsWith('#!/bin/sh\n')).toBe(true);
    // Must NOT include set -euo pipefail (research §3).
    expect(body).not.toMatch(/set\s+-e/);
    expect(body).not.toMatch(/pipefail/);
    // The terminal exec line uses absolute cli-agent path.
    expect(body).toMatch(/^exec '\/usr\/local\/bin\/cli-agent' /m);
  });

  it('bakes additionalArgs (e.g. --no-agent-tools) before "$@"', async () => {
    const result = await generateCompositeWrapperShim(
      makeSpec({ shimDir: outDir }),
      { additionalArgs: ['--no-agent-tools', '--allow-mutations', '--per-tool-budget', '65536'] },
    );
    const body = await fsp.readFile(result.path, 'utf8');
    // Each baked-in arg is single-quoted; "$@" remains the trailing token.
    expect(body).toContain(
      "exec '/usr/local/bin/cli-agent' --tool 'foo-cli' --tool 'bar-cli' " +
        "'--no-agent-tools' '--allow-mutations' '--per-tool-budget' '65536' \"$@\"",
    );
  });

  it('escapes member names with awkward characters safely', async () => {
    const result = await generateCompositeWrapperShim(
      makeSpec({
        shimDir: outDir,
        // Names a future relaxation might allow. Today's regex disallows
        // these but the generator must not regress if it ever changes.
        members: ["weird name", "it's", 'with\\backslash'],
      }),
    );
    const body = await fsp.readFile(result.path, 'utf8');
    expect(body).toContain("--tool 'weird name'");
    // Single-quote in member name → close, escaped quote, reopen.
    expect(body).toContain("--tool 'it'\\''s'");
    // Backslash is literal inside single quotes — no escaping needed.
    expect(body).toContain("--tool 'with\\backslash'");
  });

  it('escapes a doc path containing spaces and a single quote', async () => {
    const result = await generateCompositeWrapperShim(
      makeSpec({
        shimDir: outDir,
        capabilityDocPath: "/home/user's dir/doc.md",
      }),
    );
    const body = await fsp.readFile(result.path, 'utf8');
    expect(body).toContain("DOC='/home/user'\\''s dir/doc.md'");
  });
});

